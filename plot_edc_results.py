"""Plots of the consensus predictor results (predict_edc2.py).

Reads <out>_summary.csv and <out>_detail.csv (generated by predict_edc2.py) and produces:
  <out>_dashboard.png      panel with 4 alert plots
  <out>_active_fraction.png   heat map of the fraction of positive evidence units

All values use only layers in applicability domain and deployable
(column 'counted' = in_domain & ~not_deployable), the same rule as _summary.csv.

Usage:
    python plot_edc_results.py --out demo
"""
import argparse
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.ticker
import numpy as np
import pandas as pd
from matplotlib.patches import Patch, Rectangle

BASE, MEDIUM, SMALL = 10, 9, 8          # font scale (title/axes, legend, ticks)
RECEPTOR_ORDER = ["AR", "ESR1", "ESR2", "PPARG", "THRA", "THRB", "TR"]
CATEGORIES = ["n.d.", "not assessed", "no alert", "low", "moderate", "high"]
ALERT_LEVELS = ["low", "moderate", "high"]
# sequential ramp with a single hue (colorblind-safe); n.d. in hatched gray
# "not assessed" is deliberately excluded from the blue ramp: it is not a degree of alert, it is
# absence of evidence, and confusing it with "no alert" was the defect of the previous rule.
COLOR = {"n.d.": "#D9D9D9", "not assessed": "#EADCF0", "no alert": "#EEF3F8",
       "low": "#A7C7E7", "moderate": "#4F8BC9", "high": "#1B3A6B"}
TEXT_COLOR = {"n.d.": "#555555", "not assessed": "#4A2B5A", "no alert": "#333333",
             "low": "#1A1A1A", "moderate": "#FFFFFF", "high": "#FFFFFF"}

plt.rcParams.update({
    "font.size": SMALL, "axes.titlesize": BASE, "axes.labelsize": BASE,
    "xtick.labelsize": SMALL, "ytick.labelsize": SMALL, "legend.fontsize": MEDIUM,
    "figure.dpi": 100, "savefig.dpi": 300, "axes.spines.top": False,
    "axes.spines.right": False,
})


# Extract the bare alert level from the summary text; anything unrecognised becomes 'no alert'.
def _level(text):
    text = str(text)
    for n in ("high", "moderate", "low", "not assessed"):
        if text.startswith(n):
            return n
    return "no alert"


# Load the predictor outputs and build the molecule x receptor matrices; None when there is no data.
def load(out):
    """Returns dict with summary, level matrix and orderings; None if there is no data."""
    f_res, f_det = f"{out}_summary.csv", f"{out}_detail.csv"
    for f in (f_res, f_det):
        if not os.path.exists(f) or os.path.getsize(f) == 0:
            print(f"WARNING: {f} missing or empty; figures not generated")
            return None
    try:
        res = pd.read_csv(f_res)
        det = pd.read_csv(f_det)
    except pd.errors.EmptyDataError:
        print("WARNING: no molecule assessed; figures not generated")
        return None
    if res.empty or det.empty:
        print("WARNING: no molecule assessed; figures not generated")
        return None
    # from the SUMMARY, not from the detail: the saved detail file may only contain the voters
    mols = list(dict.fromkeys(res["name"].astype(str)))
    res["name"] = res["name"].astype(str)
    present = set(res["receptor"])
    recs = [r for r in RECEPTOR_ORDER if r in present] + sorted(present - set(RECEPTOR_ORDER))
    without_evidence = [r for r in dict.fromkeys(det["receptor"]) if r not in present]
    res["level"] = res["alert"].map(_level)
    cat = {(r.name, r.receptor): r.level for r in res.itertuples()}
    matrix = [[cat.get((m, rc), "n.d.") for rc in recs] for m in mols]
    return {"res": res, "mols": mols, "recs": recs, "matrix": matrix,
            "without_evidence": without_evidence}


# Draw a matrix of coloured cells with a text label inside each cell.
def _cells(ax, mols, recs, fill_color, text, text_color, hatch=None):
    """Draws a matrix of colored cells with text in each cell."""
    for i in range(len(mols)):
        for j in range(len(recs)):
            h = hatch(i, j) if hatch else None
            ax.add_patch(Rectangle((j, i), 1, 1, facecolor=fill_color(i, j), edgecolor="white",
                                   linewidth=1.5, hatch=h))
            ax.text(j + 0.5, i + 0.5, text(i, j), ha="center", va="center",
                    fontsize=SMALL, color=text_color(i, j))
    ax.set_xlim(0, len(recs))
    ax.set_ylim(len(mols), 0)
    ax.set_xticks(np.arange(len(recs)) + 0.5)
    ax.set_xticklabels(recs)
    ax.set_yticks(np.arange(len(mols)) + 0.5)
    ax.set_yticklabels(mols)
    ax.tick_params(length=0)
    for s in ax.spines.values():
        s.set_visible(False)


# Shared figure legend with one patch per alert category.
def _legend(fig, note):
    handles = [Patch(facecolor=COLOR[c], edgecolor="#888888", linewidth=0.6,
                     hatch="////" if c == "n.d." else None, label=c) for c in CATEGORIES]
    fig.legend(handles=handles, loc="lower center", ncol=len(CATEGORIES), frameon=False,
               bbox_to_anchor=(0.5, 0.035), handlelength=1.6, columnspacing=1.8)
    fig.text(0.5, 0.008, note, ha="center", va="bottom", fontsize=SMALL, color="#444444")


NOTE = ("n.d.: no layer in applicability domain. Alerts use only layers in "
        "domain and deployable.")


# Alert dashboard: one cell per molecule x receptor, coloured by alert level.
def generate_dashboard(out):
    d = load(out)
    if d is None:
        return None
    print("Generating dashboard...")
    res, mols, recs, matrix = d["res"], d["mols"], d["recs"], d["matrix"]
    nm, nr = len(mols), len(recs)
    height = max(9.0, 5.2 + 0.32 * nm)
    fig = plt.figure(figsize=(15, height))
    gs = fig.add_gridspec(2, 2, left=0.11, right=0.985, top=0.925, bottom=0.115,
                          hspace=0.42, wspace=0.30)
    fig.suptitle(f"Endocrine disruption alerts: {nm} {'molecule' if nm == 1 else 'molecules'}, "
                 f"{nr} {'receptor' if nr == 1 else 'receptors'}",
                 fontsize=BASE, fontweight="bold", x=0.11, ha="left", y=0.985)

    # (a) alert level by molecule x receptor
    ax = fig.add_subplot(gs[0, 0])
    _cells(ax, mols, recs,
             fill_color=lambda i, j: COLOR[matrix[i][j]],
             text=lambda i, j: "n.d." if matrix[i][j] == "n.d." else matrix[i][j],
             text_color=lambda i, j: TEXT_COLOR[matrix[i][j]],
             hatch=lambda i, j: "////" if matrix[i][j] == "n.d." else None)
    ax.set_title("Alert level by molecule and receptor", loc="left", pad=8)

    # (b) receptors with alert by molecule, stacked by level
    ax = fig.add_subplot(gs[0, 1])
    tally = pd.DataFrame([{n: sum(1 for x in row if x == n) for n in ALERT_LEVELS}
                         for row in matrix], index=mols)
    tally["total"] = tally.sum(axis=1)
    order = tally.assign(name=tally.index).sort_values(["total", "name"],
                                                     ascending=[False, True]).index
    tally = tally.loc[order]
    left = np.zeros(len(tally))
    for n in ALERT_LEVELS:
        ax.barh(range(len(tally)), tally[n].values, left=left, color=COLOR[n],
                edgecolor="#555555", linewidth=0.5, height=0.7)
        left += tally[n].values
    for i, t in enumerate(tally["total"].values):
        ax.text(t + 0.08, i, str(int(t)), va="center", ha="left", fontsize=SMALL)
    ax.set_yticks(range(len(tally)))
    ax.set_yticklabels(tally.index)
    ax.invert_yaxis()
    ax.set_xlim(0, nr + 0.6)
    ax.set_xticks(range(nr + 1))
    ax.set_xlabel("Receptors with alert (n)")
    ax.set_title("Receptors with alert by molecule", loc="left", pad=8)

    # (c) distribution of levels among all molecule-receptor pairs
    ax = fig.add_subplot(gs[1, 0])
    all_items = [x for row in matrix for x in row]
    n_per_category = [all_items.count(c) for c in CATEGORIES]
    ax.bar(range(len(CATEGORIES)), n_per_category, color=[COLOR[c] for c in CATEGORIES],
           edgecolor="#555555", linewidth=0.5, width=0.7,
           hatch=None)
    ax.patches[0].set_hatch("////")
    for i, v in enumerate(n_per_category):
        ax.text(i, v + max(n_per_category) * 0.02, str(v), ha="center", va="bottom", fontsize=SMALL)
    ax.set_xticks(range(len(CATEGORIES)))
    ax.set_xticklabels(CATEGORIES)
    ax.set_ylim(0, max(n_per_category) * 1.15 + 0.5)
    ax.yaxis.set_major_locator(matplotlib.ticker.MaxNLocator(integer=True))
    ax.set_ylabel("Molecule-receptor pairs (n)")
    ax.set_title("Distribution of alert levels", loc="left", pad=8)

    # (d) molecules with alert by receptor, stacked by level
    ax = fig.add_subplot(gs[1, 1])
    tally_r = pd.DataFrame([{n: sum(1 for i in range(nm) if matrix[i][j] == n)
                            for n in ALERT_LEVELS} for j in range(nr)], index=recs)
    base = np.zeros(nr)
    for n in ALERT_LEVELS:
        ax.bar(range(nr), tally_r[n].values, bottom=base, color=COLOR[n],
               edgecolor="#555555", linewidth=0.5, width=0.7)
        base += tally_r[n].values
    for i, t in enumerate(base):
        ax.text(i, t + 0.08, str(int(t)), ha="center", va="bottom", fontsize=SMALL)
    ax.set_xticks(range(nr))
    ax.set_xticklabels(recs)
    ax.set_ylim(0, nm + 0.8)
    ax.set_yticks(range(0, nm + 1, max(1, nm // 10)))
    ax.set_ylabel("Molecules with alert (n)")
    ax.set_title("Molecules with alert by receptor", loc="left", pad=8)

    note = NOTE
    if d["without_evidence"]:
        note += f" No layer in domain for any molecule: {', '.join(d['without_evidence'])}."
    _legend(fig, note)
    fname = f"{out}_dashboard.png"
    fig.savefig(fname, facecolor="white")
    plt.close(fig)
    print(f"   OK: {fname}")
    return fname


# Heat map of the active-vote fraction per molecule x receptor.
def generate_active_fraction(out):
    d = load(out)
    if d is None:
        return None
    print("Generating active fraction map...")
    res, mols, recs = d["res"], d["mols"], d["recs"]
    idx = {(r.name, r.receptor): r for r in res.itertuples()}
    cmap = plt.get_cmap("Blues")

    # Summary row for cell (i, j), or None when that pair received no votes.
    def data_item(i, j):
        return idx.get((mols[i], recs[j]))

    # Cell colour, scaled by the active-vote fraction.
    def fill_color(i, j):
        r = data_item(i, j)
        return COLOR["n.d."] if r is None else cmap(0.08 + 0.92 * r.positive_fraction)

    # Cell label: the active-vote fraction and the underlying vote counts.
    def text(i, j):
        r = data_item(i, j)
        if r is None:
            return "n.d."
        return f"{r.positive_fraction:.2f}\n{int(r.units_positive)}/{int(r.units_assessed)}"

    # Text colour chosen for contrast against the cell background.
    def txt_color(i, j):
        r = data_item(i, j)
        if r is None:
            return TEXT_COLOR["n.d."]
        return "#FFFFFF" if r.positive_fraction >= 0.55 else "#1A1A1A"

    nm, nr = len(mols), len(recs)
    fig, ax = plt.subplots(figsize=(max(8.5, 1.35 * nr + 3.5), max(6.0, 0.62 * nm + 2.6)))
    fig.subplots_adjust(left=0.17, right=0.86, top=0.90, bottom=0.17)
    _cells(ax, mols, recs, fill_color, text, txt_color,
             hatch=lambda i, j: "////" if data_item(i, j) is None else None)
    ax.set_title("Fraction of active layers per molecule and receptor", loc="left", pad=10)
    cax = fig.add_axes([0.89, 0.17, 0.022, 0.73])
    sm = plt.cm.ScalarMappable(cmap=matplotlib.colors.ListedColormap(
        cmap(np.linspace(0.08, 1.0, 256))), norm=plt.Normalize(0, 1))
    cb = fig.colorbar(sm, cax=cax)
    cb.set_label("Active / assessed layers", fontsize=BASE)
    cb.outline.set_visible(False)
    cb.ax.tick_params(labelsize=SMALL)
    note = ("Cells: fraction and (active/assessed layers). n.d.: no layer in domain.")
    if d["without_evidence"]:
        note += f"\nNo layer in domain for any molecule: {', '.join(d['without_evidence'])}."
    fig.text(0.17, 0.02, note, ha="left", va="bottom", fontsize=SMALL, color="#444444")
    fname = f"{out}_active_fraction.png"
    fig.savefig(fname, facecolor="white")
    plt.close(fig)
    print(f"   OK: {fname}")
    return fname


# Generate every figure for one prediction run.
def generate_all(out):
    print("\n" + "=" * 60)
    print("GENERATING FIGURES")
    print("=" * 60)
    if load(out) is None:
        return []
    files = [generate_dashboard(out), generate_active_fraction(out)]
    files = [a for a in files if a]
    if files:
        print("\nGenerated figures:")
        for a in files:
            print(f"   - {a}")
    return files


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True,
                    help="prefix used in predict_edc2.py (--out)")
    generate_all(ap.parse_args().out)
