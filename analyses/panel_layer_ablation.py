"""Layer ablation of the consensus on the reference panel (panel_ref.csv).

Input: panel_detail.csv generated by predict_edc2.py (default models and paths, run from inside the pipeline folder;
DO NOT pass absolute --model-dirs: the code compares the folder name as text and would label the Tox21 layer as ChEMBL).
Recomputes the alert using the same rule as predict_edc2.py (reproduces the _summary.csv) using subsets of layers and measures,
per molecule, the highest alert level among the receptors.
Usage: python panel_layer_ablation.py panel_detail.csv panel_ref.csv [dataset_ic50.csv] [pipeline_folder]
"""
import sys, glob
import numpy as np, pandas as pd

det_csv, panel_csv = sys.argv[1], sys.argv[2]
ic50_csv = sys.argv[3] if len(sys.argv) > 3 else None
pipe = sys.argv[4] if len(sys.argv) > 4 else None
ORD = ["no alert", "low", "moderate", "high"]
LEVEL_RANK = {k: i for i, k in enumerate(ORD)}

d = pd.read_csv(det_csv)
for c in ("counted", "active"):
    d[c] = d[c].astype(str).str.lower().eq("true")
cls = pd.read_csv(panel_csv).set_index("name").class_label
d["group"] = np.where(d.layer == "Tox21", "Tox21", d.layer.str.replace("ChEMBL ", ""))


# Recompute the alert level of every molecule x receptor pair from the per-model votes.
def alert(v):
    v = v[v.counted].copy()
    v["pharm"] = v.layer.str.startswith("ChEMBL")
    v["f"], v["t"] = v.pharm & v.active, (~v.pharm) & v.active
    r = v.groupby(["name", "receptor"]).agg(n_assessed=("endpoint", "nunique"), n_active=("active", "sum"), ef=("f", "sum"), et=("t", "sum")).reset_index()
    r["fr"] = r.n_active / r.n_assessed
    r["alert"] = np.select([(r.n_active >= 2) & (r.ef >= 1) & (r.et >= 1), (r.fr >= .5) & (r.n_assessed >= 3), r.n_active >= 1], ["high", "moderate", "low"], "no alert")
    return r


CFG = {"All layers (current)": ["IC50", "Ki", "Kd", "EC50", "Tox21"], "Without Tox21 (IC50 + Ki/Kd/EC50)": ["IC50", "Ki", "Kd", "EC50"],
       "Without Ki/Kd/EC50 (IC50 + Tox21)": ["IC50", "Tox21"], "ChEMBL IC50 only": ["IC50"], "ChEMBL Ki/Kd/EC50 only": ["Ki", "Kd", "EC50"], "Tox21 only": ["Tox21"]}
mols = sorted(d.name.unique())
neg_cls = ("negative control", "non-EDC drug control")
pos = [n for n in mols if cls[n] not in neg_cls]
neg = [n for n in mols if n not in pos]

maxlv, rows = {}, []
for name, g in CFG.items():
    a = alert(d[d.group.isin(g)])
    mx = a.assign(lv=a.alert.map(LEVEL_RANK)).groupby("name").lv.max().reindex(mols).fillna(0).astype(int)
    maxlv[name] = mx
    for lim, lab in ((1, "≥ low"), (2, "≥ moderate"), (3, "high")):
        rows.append(dict(config=name, threshold=lab, detected_positives=int((mx[pos] >= lim).sum()), n_positives=len(pos),
                         flagged_negatives=int((mx[neg] >= lim).sum()), n_negatives=len(neg)))
pd.DataFrame(rows).to_csv("panel_layer_ablation_summary.csv", index=False)
pd.DataFrame({k: v.map(lambda i: ORD[i]) for k, v in maxlv.items()}).assign(class_label=cls.reindex(mols)).to_csv("panel_layer_ablation_by_molecule.csv")

if ic50_csv and pipe:   # presence in training (first block of the InChIKey = connectivity)
    ik = d.drop_duplicates("name").set_index("name").inchikey
    b14 = lambda s: {x[:14] for x in s.dropna()}
    kc = lambda fs: b14(pd.concat([pd.read_csv(f, usecols=["inchikey"]).inchikey for f in fs]))
    S = {"IC50": b14(pd.read_csv(ic50_csv, usecols=["inchikey"], low_memory=False).inchikey),
         "Ki/Kd/EC50": kc(glob.glob(pipe + "/datasets_layers_by_endpoint/dataset_*.csv")),
         "Tox21": kc(glob.glob(pipe + "/datasets_tox21_by_assay/dataset_*.csv"))}
    tab = pd.DataFrame({k: [ik[n][:14] in S[k] for n in mols] for k in S}, index=mols)
    tab.assign(class_label=cls.reindex(mols)).to_csv("panel_presence_in_training.csv")
    outside = [n for n in pos if not tab.loc[n, ["IC50", "Ki/Kd/EC50"]].any()]
    inside = [n for n in pos if n not in outside]
    out = []
    for name in ("ChEMBL IC50 only", "ChEMBL Ki/Kd/EC50 only", "Without Tox21 (IC50 + Ki/Kd/EC50)"):
        for lim, lab in ((1, "≥ low"), (2, "≥ moderate")):
            out.append(dict(config=name, threshold=lab, out_of_chembl_training=f"{int((maxlv[name][outside] >= lim).sum())}/{len(outside)}",
                            within_chembl_training=f"{int((maxlv[name][inside] >= lim).sum())}/{len(inside)}"))
    pd.DataFrame(out).to_csv("ablation_chembl_in_out_of_training.csv", index=False)
print("OK", len(mols), "molecules;", len(pos), "positive;", len(neg), "negatives")
